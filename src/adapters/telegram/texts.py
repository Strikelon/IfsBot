# --- LLM error helper ---


def llm_error_message(category: ErrorCategory | None) -> str:
    """Map ErrorCategory → user-facing UX text. None defaults to TRANSIENT."""
    # Import here to avoid circular imports (texts ← generator ← texts cycle).
    from llm.generator import ErrorCategory  # noqa: PLC0415

    if category == ErrorCategory.CONTENT_FILTER:
        return LLM_ERROR_CONTENT_FILTER
    if category == ErrorCategory.QUOTA_EXCEEDED:
        return LLM_ERROR_QUOTA
    if category == ErrorCategory.PERMANENT:
        return LLM_ERROR_PERMANENT
    return LLM_ERROR_TRANSIENT


