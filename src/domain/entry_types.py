ENTRY_TYPES: dict[str, EntryTypeConfig] = {
    KIND_DREAM: _DREAM,
    KIND_SITUATION: _SITUATION,
    KIND_CONFLICT: _CONFLICT,
}


def entry_config(kind: str | None) -> EntryTypeConfig:
    """Конфиг по kind; незнакомое/пустое значение → dream (fail-safe).

    Fail-safe важен для легаси-путей: любой старый вызов без kind обязан вести
    себя ровно как ветка сна до фичи.
    """
    return ENTRY_TYPES.get(kind or KIND_DREAM, ENTRY_TYPES[KIND_DREAM])
