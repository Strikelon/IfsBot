"""Реестр типов обращения (спека B2): единый объект на тип.

Тип обращения (dreams.kind): dream / external_situation / internal_conflict.
Здесь — только чистые данные (тексты, команды, наборы статусов). Промпт-модули
на тип живут в src/llm/prompts/entry_prompts.py (слой llm), хэндлеры — в adapters.

ВАЖНО (слойность): domain не импортирует adapters, поэтому dream-конфиг дублирует
константы texts.py литералами. Байт-паритет закреплён tests/unit/test_entry_types.py
(test_dream_config_is_byte_identical_to_texts_constants) — при правке текста сна
менять ОБА места, тест не даст разъехаться.
"""

from __future__ import annotations

from dataclasses import dataclass

KIND_DREAM = "dream"
KIND_SITUATION = "external_situation"
KIND_CONFLICT = "internal_conflict"
ALL_KINDS: tuple[str, ...] = (KIND_DREAM, KIND_SITUATION, KIND_CONFLICT)


@dataclass(frozen=True)
class EntryTypeConfig:
    """Все текстовые/командные различия одного типа обращения."""

    kind: str
    label: str                      # текст кнопки на экране выбора
    onb_invite: str                 # приглашение рассказать (онбординг), {name}
    repeat_invite: str              # приглашение рассказать (повторное, /new_*)
    loop_prompt: str                # «Записал. Хотите рассказать ещё…»
    per_session_question: str       # вопрос про переживания (аналог per_session_context)
    preq_offer_text: str            # приглашение к 1–3 вопросам (offer-first)
    preq_tmpl_many: str             # шаблон вопроса при total>=2 ({n},{total},{name},{question})
    preq_tmpl_one: str              # шаблон единственного вопроса ({name},{question})
    preq_unclear: str               # переспрос на приглашении
    thinking_statuses: tuple[str, ...]       # «думающие» статусы разбора/Q&A
    preq_thinking_statuses: tuple[str, ...]  # статусы на время генерации вопросов
    cf_analysis: str                # контент-фильтр: обычный разбор
    cf_onboarding: str              # контент-фильтр: онбординг
    cf_qa: str                      # контент-фильтр: круг Q&A
    already_active: str             # «уже идёт разбор»
    auto_paused_notice: str         # авто-пауза при уходе в другое место
    card_title_tmpl: str            # карточка: {date}, {transcription}
    list_header: str                # заголовок списка: {count}
    list_empty: str                 # пустой список
    confirm_analyze_prompt: str     # гейт «Разобрать сейчас?» на карточке
    saved_without_analysis: str     # «Сохранил. Открыть список – …»
    delete_confirm_1: str           # {date}
    delete_confirm_2: str
    deleted_notice: str
    new_command: str                # команда нового обращения (без «/»)
    list_command: str               # команда списка (без «/»)
    phase_pre_q: str                # llm_phase_label пре-initial вопросов


