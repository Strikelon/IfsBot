async def classify_entry_answer_intent(
    *, client: AsyncOpenAI, model: str, user_text: str, bot_question: str
) -> IntentResult:
    """Ответ на пре-вопрос для НЕ-сновых типов: answer/skip/question. Дефолт — answer.

    Отдельный от `classify_image_answer_intent`: тот в системном промпте и во всех
    примерах привязан к образам сна, а его поле `answer` при outcome="question"
    показывается юзеру ДОСЛОВНО — человек, разбирающий конфликт в семье, получил бы
    переспрос про сон. Гарды те же: длинная реплика → answer без вызова модели.
    """
    stripped = user_text.strip()
    if len(stripped) > IMAGE_ANSWER_MAX_INTENT_CHARS:
        return IntentResult(outcome="answer", input_tokens=0, output_tokens=0)
    composed = f"[вопрос бота] {bot_question.strip()}\n[ответ юзера] {stripped}"
    messages = _build_messages(_ENTRY_ANSWER_SYSTEM, _ENTRY_ANSWER_FEWSHOT, composed)
    return await _classify_with_default(
        client=client, model=model, messages=messages, schema=_ImageAnswerIntent,
        default_outcome="answer", kind="entry_answer",
    )


_BRANCH_COMPRESS_SYSTEM = """\
Ты сжимаешь запрос пользователя. Юзер своими словами описал, ЧТО он хочет получить \
от разбора своего сна. Переформулируй это в одну короткую ёмкую фразу (до ~120 \
символов), от первого лица, сохранив суть запроса. Не интерпретируй сон, не \
добавляй ничего от себя.

Отвечай ТОЛЬКО строгим JSON, без markdown и ```-фенсов:
{"request": "короткая формулировка"}\
"""


@dataclass(frozen=True)
class BranchRequest:
    text: str
    input_tokens: int
    output_tokens: int


async def compress_branch_request(
    *, client: AsyncOpenAI, model: str, user_text: str
) -> BranchRequest:
    """Точка 3: если кастомный запрос ветки слишком длинный — сжать дешёвой моделью.

    Короткий запрос возвращается как есть (без вызова модели, tokens=0). При сбое
    сжатия — возвращаем обрезанный исходник (UX не ломается).
    """
    stripped = user_text.strip()
    if len(stripped) <= BRANCH_REQUEST_MAX_CHARS:
        return BranchRequest(text=stripped, input_tokens=0, output_tokens=0)

    messages = [
        {"role": "system", "content": _BRANCH_COMPRESS_SYSTEM},
        {"role": "user", "content": stripped},
    ]
    try:
        res = await classify(
            client=client, model=model, messages=messages, schema=_BranchSummary
        )
    except Exception:  # noqa: BLE001
        log.warning("intent.branch_compress_failed", exc_info=True)
        return BranchRequest(
            text=stripped[:BRANCH_REQUEST_MAX_CHARS], input_tokens=0, output_tokens=0
        )
    return BranchRequest(
        text=res.parsed.request.strip(),
        input_tokens=res.input_tokens,
        output_tokens=res.output_tokens,
    )
