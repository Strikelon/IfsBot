"""Intent-классификаторы для точек, где раньше был только тап кнопки.

Дешёвая модель (gpt-4o-mini по умолчанию, см. settings.openrouter_intent_model)
определяет НАМЕРЕНИЕ свободной реплики юзера (текст или расшифрованный голос):

- LOOP (точки 1&2): юзер в LIFE_CONTEXT_LOOP / DREAM_LOOP — продолжает рассказ,
  сигналит «всё, дальше» или задаёт встречный вопрос про шаг.
  outcome ∈ {continue, done, question}; при question — поле `answer` с ответом.
- QA (точка 4): юзер в IN_QA после разбора — продолжает диалог (вопрос, КОММЕНТАРИЙ,
  размышление, реакция) или завершает. outcome ∈ {continue, finish, new_dream}.
- CONFIRM (точка 5): юзер на гейте нового сна — разобрать сейчас, сохранить без
  разбора, встречный вопрос или непонятно. outcome ∈ {analyze, save, question, unclear}.

Дисциплина полей (см. memory classifier-field-discipline): downstream-логика
смотрит ТОЛЬКО на `outcome` (строгий Literal). `reason` — для логов, никогда не
передаётся как structured input дальше.

Безопасные дефолты при сбое сети/парсинга (потеря намерения не должна ломать UX):
- LOOP → continue (не теряем контент юзера; «Это всё» он всегда может тапнуть);
- QA → continue (ошибочно закрыть сессию хуже, чем ответить лишний раз);
- CONFIRM → unclear (не угадываем между платным разбором и сохранением — переспросим).

Также: compress_branch_request — сжатие слишком длинного кастомного запроса ветки
в короткую формулировку той же дешёвой моделью (точка 3).
"""

