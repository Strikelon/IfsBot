def _build_messages(
    system: str, fewshot: list[tuple[str, str]], user_text: str
) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = [{"role": "system", "content": system}]
    for user_ex, assistant_ex in fewshot:
        messages.append({"role": "user", "content": f"Реплика: «{user_ex}»"})
        messages.append({"role": "assistant", "content": assistant_ex})
    messages.append({"role": "user", "content": f"Реплика: «{user_text}»"})
    return messages


async def _classify_with_default[T: BaseModel](
    *,
    client: AsyncOpenAI,
    model: str,
    messages: list[dict[str, Any]],
    schema: type[T],
    default_outcome: str,
    kind: str,
) -> IntentResult:
    """Вызвать classify(); при ЛЮБОМ сбое вернуть безопасный дефолт с tokens=0."""
    try:
        res = await classify(client=client, model=model, messages=messages, schema=schema)
    except ClassifierParseError:
        log.warning("intent.parse_failed", kind=kind, default=default_outcome)
        return IntentResult(outcome=default_outcome, input_tokens=0, output_tokens=0)
    except Exception:  # noqa: BLE001 — сеть/таймаут/прочее: не роняем UX
        log.warning("intent.call_failed", kind=kind, default=default_outcome, exc_info=True)
        return IntentResult(outcome=default_outcome, input_tokens=0, output_tokens=0)
    return IntentResult(
        outcome=res.parsed.outcome,  # type: ignore[attr-defined]
        input_tokens=res.input_tokens,
        output_tokens=res.output_tokens,
        answer=getattr(res.parsed, "answer", "") or "",
        told=bool(getattr(res.parsed, "told", False)),
    )


