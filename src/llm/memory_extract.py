# Порог: совпало ≥ 3/4 всех значимых слов обеих записей (Жаккар ≥ 0.75). Выбран
# консервативно — лучше пропустить дубль, чем склеить два разных факта: при таком
# пороге ОДНО отличающееся значимое слово в записи из четырёх слов (3 общих из 5 в
# объединении = 0.6) уже разводит записи («учит испанский» / «учит английский»,
# «мать живёт в Москве» / «отец живёт в Москве»). Схлопываются в основном
# перестановки и добавления служебных деталей.
_DEDUP_NUM, _DEDUP_DEN = 3, 4
# Меньше трёх значимых слов — множества слишком грубые (одно слово из двух даёт 0.5,
# два — сразу 1.0), перефразный дедуп не применяем вовсе, остаётся дословный.
_DEDUP_MIN_SIGNIFICANT = 3
_WORD_RE = re.compile(r"[\w\-]+", re.UNICODE)


# --- Безличные формулировки: слово «юзер» вон из текста записи (2026-08-16) ---
# Корень проблемы рода: «юзер» — слово мужского рода, оно тянет за собой
# согласование, и про женщин писалось «Юзер оплатил», «пережил рецидив».
# Правилами в промпте не лечится (проверено: после усиления правила стало ХУЖЕ,
# 4 → 10 записей с мужским родом). Запись по определению про юзера — подлежащее
# не нужно. Промпт просит писать без него, а этот регексп подчищает остатки:
# «У юзера есть дочь» → «Есть дочь», «Подруга отвезла юзера» → «Подруга отвезла».
# Побочно экономит место в блоке памяти.
_USER_WORD_RE = re.compile(
    r"(?:\bу\s+)?\b(?:юзер|пользовател)[а-яё]*\b\s*", re.IGNORECASE
)
_SPACE_BEFORE_PUNCT_RE = re.compile(r"\s+([,.;:!?])")


def _depersonalize(text: str) -> str:
    """Убрать слово «юзер»/«пользователь» из записи, сохранив читаемую фразу."""
    cleaned = _USER_WORD_RE.sub("", text or "")
    cleaned = _SPACE_BEFORE_PUNCT_RE.sub(r"\1", cleaned)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned).strip()
    if cleaned and cleaned != text:
        cleaned = cleaned[0].upper() + cleaned[1:]
    return cleaned


def _norm(text: str) -> str:
    """Нормализация текста для дедупа: регистр, пробелы, финальная пунктуация."""
    return re.sub(r"\s+", " ", (text or "").strip().lower()).rstrip(".!?;,: ")


def _significant_words(text: str) -> frozenset[str]:
    """Множество ОСНОВ значимых слов: без пунктуации, стоп-слов и коротких слов.

    Отбор идёт по целому слову (длина, стоп-лист), а в множество кладётся начало
    слова — так словоформы одного корня становятся одним элементом.
    """
    return frozenset(
        w[:_DEDUP_STEM_LEN]
        for w in _WORD_RE.findall(_norm(text))
        if (len(w) >= _DEDUP_MIN_WORD_LEN or any(ch.isdigit() for ch in w))
        and w not in _DEDUP_STOPWORDS
    )


def _is_paraphrase(a: frozenset[str], b: frozenset[str]) -> bool:
    """Две записи — перефраз одного факта (пересечение значимых слов выше порога)."""
    if len(a) < _DEDUP_MIN_SIGNIFICANT or len(b) < _DEDUP_MIN_SIGNIFICANT:
        return False
    union = len(a | b)
    if not union:
        return False
    # Рациональное сравнение вместо float: |a∩b| / |a∪b| >= 3/4.
    return len(a & b) * _DEDUP_DEN >= union * _DEDUP_NUM


def _slug_from_text(text: str) -> str:
    """Детерминированный латинский слаг из текста части, в пределах String(64)."""
    chars: list[str] = []
    for ch in (text or "").lower():
        if ch in _TRANSLIT:
            chars.append(_TRANSLIT[ch])
        elif ch.isascii() and ch.isalnum():
            chars.append(ch)
        else:
            chars.append("-")
    slug = re.sub(r"-+", "-", "".join(chars)).strip("-")
    return slug[:_MAX_ENTITY_KEY].strip("-")


