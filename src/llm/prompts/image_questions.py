"""Выделение 1–3 ярких образов сна + заземляющие вопросы (image_questions.v1).

Отдельный вызов ДО initial-разбора по цепочке генератора (flash→pro→haiku).
Выход — строгий JSON {"images":[{"name","question"}]}; безопасный дефолт при
любом сбое — 0 образов → молча обычный разбор (паттерн split_qa_options).
Палитра вопросов — заземление v3.11 из _SYSTEM_FOLLOWUP (prompts/quick.py).
При изменении ЛЮБОГО текста промпта — инкрементировать IMAGE_QUESTIONS_VERSION.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from llm.classifier import _strip_fences
from llm.prompts.quick import Message, QuickContext, _user_block

IMAGE_QUESTIONS_VERSION = "image_questions.v1"

_MAX_IMAGES = 3
# Обрезка одного ответа юзера в блоке initial-промпта (краевой случай №13 спеки).
_MAX_ANSWER_CHARS = 600


@dataclass(frozen=True)
class ImageQuestion:
    name: str
    question: str


_SYSTEM_IMAGE_QUESTIONS = """\
Ты — ассистент-психолог, который готовится к разбору сна. Юзер уже рассказал сон \
и то, что его волновало. ПЕРЕД разбором твоя задача: выбрать 1–3 САМЫХ ярких, \
эмоционально заряженных образа этого сна и к каждому сформулировать РОВНО ОДИН \
открытый заземляющий вопрос — о том, как этот образ живёт в РЕАЛЬНОЙ ЖИЗНИ юзера \
(не во сне). Ответы юзера сделают последующий разбор точнее.

Как выбирать образы:
- Яркость и эмоциональный заряд: персонажи, существа, значимые предметы и места, \
вокруг которых крутится действие или чувство сна.
- 1–3 образа. Если ярких образов меньше трёх — верни меньше: один сильный образ \
лучше трёх вялых.
- ПРАВИЛО ЗНАКОМЫХ ОБРАЗОВ: если из блока «ЧТО УЖЕ ИЗВЕСТНО ИЗ ПРОШЛЫХ РАЗБОРОВ», \
из профиля или из рассказа юзера УЖЕ ясно, как образ связан с его реальной жизнью — \
НЕ выбирай этот образ. НО: если ярких образов мало и все они знакомые — лучше задай \
вопрос про знакомый образ, чем вернуть пустой список.

Как формулировать вопрос (ровно ОДИН на образ; выбери формулировку из палитры, \
которая лучше подходит под образ):
1) Отношение/характеристика: «Как бы вы охарактеризовали ваши отношения с отцом \
в реальности?»
2) Эмоции в реальности: «Какие эмоции у вас вызывают красивые автомобили в реальности?»
3) Значимые события за месяц: «Что в последний месяц происходило в вашей жизни, \
что связано с образом воды?»
4) Проективный смысл: «Что, по-вашему, красивые автомобили говорят об их владельцах?»

ЖЕЛЕЗНОЕ ПРАВИЛО — вопрос про САМ образ, а не про твою расшифровку:
- Спрашивай про буквальный объект/существо/человека/место из сна (вампир, собаки, \
руководитель, автомобиль) — как он существует в РЕАЛЬНОЙ жизни юзера: отношение юзера \
к нему, эмоции и ассоциации, которые он вызывает, реальные события и аналоги, \
связанные именно с ним.
- НЕ подменяй образ своей интерпретацией. Запрещено сначала решить за юзера, что образ \
«значит/символизирует/олицетворяет», и спросить про это значение. Формулировки вида \
«что ощущается как <твоя расшифровка>» или «кто в вашей жизни как <роль>», где само \
слово-образ выпало из вопроса, — под запретом: смысл образа должен назвать ЮЗЕР, не ты.
- Слово, называющее образ, ОБЯЗАНО присутствовать в вопросе, и вопрос — прямо о нём.
- Предпочитай формулировки 1–3 из палитры. Формулировка 4 (проективный смысл) допустима \
ТОЛЬКО пока она остаётся буквально про образ — про то, что этот объект вообще означает \
в реальности, — а НЕ про твою расшифровку именно этого сна.

Пример для образа «Вампир»:
- ПЛОХО (образ подменён интерпретацией): «Какие люди или обстоятельства в вашей \
реальной жизни сейчас ощущаются как скрытая угроза, забирающая ваши силы?»
- ХОРОШО (про сам образ): «Как вы в реальной жизни относитесь к вампирам — какие \
эмоции и ассоциации они у вас вызывают?»

Требования к вопросу:
- Открытый (не да/нет), про РЕАЛЬНУЮ жизнь юзера, а не про сон.
- На «вы», тёплый, простой язык, без эмодзи, одно предложение.

ЗАПРЕЩЕНО:
- Любая интерпретация сна («этот образ значит…», «символизирует…») — на этом шаге \
ты ТОЛЬКО задаёшь вопросы.
- Подмена образа его предполагаемым смыслом (см. железное правило выше).
- Вопросы про сам сон («что было дальше во сне?», «каким был тигр во сне?»).
- Больше одного вопроса на образ; сдвоенные вопросы через «и/или».

Имя образа (name): 2–4 слова, до 25 символов, именительный падеж, без кавычек и \
пояснений в скобках. Плохо: «Старый автомобиль отца (из гаража)». Хорошо: \
«Старый автомобиль».

Формат ответа — ТОЛЬКО строгий JSON без markdown и ```-фенсов, одной строкой:
{"images":[{"name":"...","question":"..."}]}
0–3 элемента. Если подходящих образов нет — {"images":[]}.\
"""


def build_image_questions_messages(ctx: QuickContext) -> list[Message]:
    """System + тот же user-блок, что у initial (профиль, память, запрос, сон)."""
    return [
        {"role": "system", "content": _SYSTEM_IMAGE_QUESTIONS},
        {"role": "user", "content": _user_block(ctx)},
    ]


def parse_image_questions(raw: str) -> tuple[list[ImageQuestion], str | None]:
    """Распарсить строгий JSON выделения образов. Никогда не бросает.

    Returns:
        (items, fail_reason):
        - успех с ≥1 образом → (items, None); >3 элементов обрезаются до 3;
        - валидный JSON, но 0 валидных образов → ([], "empty");
        - битый JSON / не-dict / images не список → ([], "parse_error").
    """
    try:
        payload = json.loads(_strip_fences(raw.strip()))
    except (json.JSONDecodeError, ValueError):
        return [], "parse_error"
    if not isinstance(payload, dict):
        return [], "parse_error"
    images = payload.get("images")
    if not isinstance(images, list):
        return [], "parse_error"
    out: list[ImageQuestion] = []
    for item in images:
        if not isinstance(item, dict):
            continue
        name = item.get("name")
        question = item.get("question")
        if not isinstance(name, str) or not isinstance(question, str):
            continue
        name, question = name.strip(), question.strip()
        if not name or not question:
            continue
        out.append(ImageQuestion(name=name, question=question))
        if len(out) >= _MAX_IMAGES:
            break
    if not out:
        return [], "empty"
    return out, None


def build_image_answers_block(items: list[dict]) -> str:
    """Блок «что юзер рассказал об образах» для initial-промпта (Task 12).

    Только отвеченные items (answer непустой); скипы и мета-диалог не попадают.
    Пустая строка = блок не подставляется (промпт как без фичи).
    """
    answered = [
        i for i in items
        if isinstance(i, dict) and isinstance(i.get("answer"), str) and i["answer"].strip()
    ]
    if not answered:
        return ""
    lines = [
        "ЧТО ПОЛЬЗОВАТЕЛЬ РАССКАЗАЛ О КЛЮЧЕВЫХ ОБРАЗАХ СНА "
        "(о своей РЕАЛЬНОЙ жизни, собрано до разбора):"
    ]
    for it in answered:
        answer = it["answer"].strip()[:_MAX_ANSWER_CHARS]
        lines.append(f'– Образ "{str(it.get("name", "")).strip()}": {answer}')
    return "\n".join(lines)
