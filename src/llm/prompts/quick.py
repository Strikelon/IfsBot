QA_OPTIONS_SENTINEL = "===QA_OPTIONS==="
_QA_MAX_OPTIONS = 2

# Детерминированный гард: чипы-варианты НИКОГДА не должны дублировать фиксированную
# кнопку завершения (QA_FINISH_BTN = «✅ Сохранить и разобрать новое»).
# Промпт это запрещает (см. _SYSTEM_*: «завершение — только через стандартную кнопку
# снизу»), но генератор иногда «протекает» вариантом вроде «Подвести итог сна» /
# «Завершить разбор». Любой option, чей нормализованный текст матчит этот паттерн,
# выкидывается ещё на парсинге — до сборки клавиатуры.
_FINISH_DUPE_RE = re.compile(
    r"заверш|сохран|подыто[жг]|подвести\s+итог|итог[аои]?\s+сна|"
    r"закончит|вернус[ьъ]?\s+позже|верн[её]мся\s+позже|вернут[ьъ]?ся\s+позже|"
    r"верн[её]тес[ьъ]?\s+позже|на\s+сегодня",
    re.IGNORECASE,
)


def _is_finish_dupe(label: str) -> bool:
    """True, если лейбл-вариант дублирует завершение/сохранение разбора."""
    normalized = re.sub(r"[^\w\s]", " ", label).strip()
    return bool(_FINISH_DUPE_RE.search(normalized))


def split_qa_options(raw: str) -> tuple[str, str, list[str], dict | None]:
    """Разрезать ответ генератора на прозу и машиночитаемый хвост.

    Формат хвоста:
        ===QA_OPTIONS===
        {"kind":"choice"|"confirm"|"clarify", "options":[...], "map":{...}}

    Returns (prose, kind, options, qa_map):
        - prose: текст разбора без хвоста (.strip()).
        - kind: "choice" | "confirm" | "clarify". При любой ошибке — "choice".
        - options: для choice ≤2 непустых строк-лейблов; иначе [].
        - qa_map: dict карты беседы из ключа "map", либо None (нет/не dict).
    Безопасный дефолт при отсутствии сентинела / битом JSON / неизвестном kind:
        (prose_or_raw, "choice", [], None).
    """
    if QA_OPTIONS_SENTINEL not in raw:
        return raw.strip(), "choice", [], None
    prose, _, tail = raw.partition(QA_OPTIONS_SENTINEL)
    prose = prose.strip()
    try:
        payload = json.loads(_strip_fences(tail.strip()))
    except (json.JSONDecodeError, ValueError):
        return prose, "choice", [], None
    if not isinstance(payload, dict):
        return prose, "choice", [], None
    raw_map = payload.get("map")
    qa_map = raw_map if isinstance(raw_map, dict) else None
    kind = payload.get("kind")
    if kind not in ("choice", "confirm", "clarify"):
        return prose, "choice", [], qa_map
    if kind in ("confirm", "clarify"):
        return prose, kind, [], qa_map
    raw_options = payload.get("options")
    if not isinstance(raw_options, list):
        return prose, "choice", [], qa_map
    options = [
        o.strip()
        for o in raw_options
        if isinstance(o, str) and o.strip() and not _is_finish_dupe(o)
    ]
    return prose, "choice", options[:_QA_MAX_OPTIONS], qa_map


